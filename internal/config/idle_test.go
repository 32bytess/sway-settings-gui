func TestIdleDisabledByDefault(t *testing.T) {
	setupHome(t)
	cfg, err := Load()
	if err != nil {
		t.Fatal(err)
	}
	if cfg.Idle.Enabled {
		t.Fatal("idle should be off by default")
	}
	if cfg.Idle.LockMinutes != 5 || cfg.Idle.ScreenOffMinutes != 10 || cfg.Idle.SuspendMinutes != 0 ||
		!cfg.Idle.LockBeforeSleep || cfg.Idle.LockColor != "000000" {
		t.Fatalf("unexpected idle defaults: %+v", cfg.Idle)
	}
	if err := cfg.Save(); err != nil {
		t.Fatal(err)
	}
	if got := readFile(t, IdlePath()); got != "" {
		t.Fatalf("idle.conf = %q, want empty", got)
	}
	if _, err := os.Stat(IdleScriptPath()); !errors.Is(err, os.ErrNotExist) {
		t.Fatalf("script should not be written while disabled (stat err %v)", err)
	}
}

func TestIdleEnabledWritesScriptAndInclude(t *testing.T) {
	setupHome(t)
	cfg, err := Load()
	if err != nil {
		t.Fatal(err)
	}
	cfg.Idle.Enabled = true
	cfg.Idle.LockColor = "1E1E2E"
	cfg.Idle.LockImage = "/home/me/My Pictures/lock.png"
	cfg.Idle.ShowFailedAttempts = true
	cfg.Idle.SuspendMinutes = 30
	if err := cfg.Save(); err != nil {
		t.Fatal(err)
	}
	if got := readFile(t, IdlePath()); got != "exec_always "+IdleScriptPath()+"\n" {
		t.Fatalf("idle.conf = %q", got)
	}
	info, err := os.Stat(IdleScriptPath())
	if err != nil {
		t.Fatal(err)
	}
	if info.Mode().Perm()&0100 == 0 {
		t.Fatalf("script not executable: %v", info.Mode())
	}
	lock := `swaylock -f -c 1E1E2E -i '\''/home/me/My Pictures/lock.png'\'' -F`
	want := `#!/bin/bash
# Generated by sway-settings. Change these settings in the app.
# lock_minutes=5
# screen_off_minutes=10
# suspend_minutes=30
# lock_before_sleep=yes
# lock_color=1E1E2E
# lock_image=/home/me/My Pictures/lock.png
# show_failed_attempts=yes
# ignore_empty_password=no
pkill -f '^sway-settings-idle( |$)'
exec -a sway-settings-idle swayidle -w \
    timeout 300 '` + lock + `' \
    timeout 600 'swaymsg "output * power off"' resume 'swaymsg "output * power on"' \
    timeout 1800 'systemctl suspend' \
    before-sleep '` + lock + `'
`
	if got := readFile(t, IdleScriptPath()); got != want {
		t.Fatalf("script =\n%s\nwant\n%s", got, want)
	}
}

func TestIdleRoundTripAndDisable(t *testing.T) {
	setupHome(t)
	cfg, err := Load()
	if err != nil {
		t.Fatal(err)
	}
	cfg.Idle.Enabled = true
	cfg.Idle.LockMinutes = 3
	cfg.Idle.ScreenOffMinutes = 0
	cfg.Idle.LockBeforeSleep = false
	cfg.Idle.IgnoreEmptyPassword = true
	if err := cfg.Save(); err != nil {
		t.Fatal(err)
	}
	again, err := Load()
	if err != nil {
		t.Fatal(err)
	}
	want := cfg.Idle
	if !reflect.DeepEqual(again.Idle, want) {
		t.Fatalf("round trip:\n got %+v\nwant %+v", again.Idle, want)
	}
	script := readFile(t, IdleScriptPath())
	if strings.Contains(script, "power off") || strings.Contains(script, "before-sleep") {
		t.Fatalf("disabled actions written:\n%s", script)
	}

	again.Idle.Enabled = false
	if err := again.Save(); err != nil {
		t.Fatal(err)
	}
	if got := readFile(t, IdlePath()); got != "" {
		t.Fatalf("idle.conf = %q after disabling", got)
	}
	third, err := Load()
	if err != nil {
		t.Fatal(err)
	}
	if third.Idle.Enabled || third.Idle.LockMinutes != 3 {
		t.Fatalf("disabled idle should keep its settings: %+v", third.Idle)
	}
}

func TestIdleValidation(t *testing.T) {
	cases := []func(*Idle){
		func(i *Idle) { i.LockMinutes = -1 },
		func(i *Idle) { i.SuspendMinutes = 100000 },
		func(i *Idle) { i.LockColor = "#000000" },
		func(i *Idle) { i.LockColor = "black" },
		func(i *Idle) { i.LockImage = "/a\nb" },
	}
	for _, mutate := range cases {
		setupHome(t)
		cfg, err := Load()
		if err != nil {
			t.Fatal(err)
		}
		cfg.Idle.Enabled = true
		mutate(&cfg.Idle)
		if err := cfg.Save(); err == nil {
			t.Errorf("expected error for %+v", cfg.Idle)
		}
	}
}

func TestStopIdleAndLockNow(t *testing.T) {
	orig := runCommand
	t.Cleanup(func() { runCommand = orig })
	var calls [][]string
	runCommand = func(name string, args ...string) (int, error) {
		calls = append(calls, append([]string{name}, args...))
		return 1, nil // pkill: nothing matched
	}
	if err := StopIdle(); err != nil {
		t.Fatalf("no swayidle running is not an error: %v", err)
	}
	if !reflect.DeepEqual(calls[0], []string{"pkill", "-f", "^sway-settings-idle( |$)"}) {
		t.Fatalf("pkill call = %q", calls[0])
	}
	runCommand = func(name string, args ...string) (int, error) { return 2, nil }
	if err := StopIdle(); err == nil {
		t.Fatal("pkill exit 2 should be an error")
	}

	calls = nil
	runCommand = func(name string, args ...string) (int, error) {
		calls = append(calls, append([]string{name}, args...))
		return 0, nil
	}
	idle := Idle{LockColor: "1E1E2E", LockImage: "/a b.png", ShowFailedAttempts: true}
	if err := LockNow(idle); err != nil {
		t.Fatal(err)
	}
	want := []string{"swaylock", "-f", "-c", "1E1E2E", "-i", "/a b.png", "-F"}
	if !reflect.DeepEqual(calls[0], want) {
		t.Fatalf("swaylock call = %q, want %q", calls[0], want)
	}
	runCommand = func(name string, args ...string) (int, error) { return 1, nil }
	if err := LockNow(idle); err == nil {
		t.Fatal("swaylock failure should be an error")
	}
}

func TestLXQtIdleWatcherEnabled(t *testing.T) {
	home := setupHome(t)
	if on, err := LXQtIdleWatcherEnabled(); err != nil || on {
		t.Fatalf("missing file: got %v, %v", on, err)
	}
	p := filepath.Join(home, ".config", "lxqt", "lxqt-powermanagement.conf")
	if err := os.MkdirAll(filepath.Dir(p), 0755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte("[General]\nenableIdlenessWatcher=true\n"), 0644); err != nil {
		t.Fatal(err)
	}
	if on, err := LXQtIdleWatcherEnabled(); err != nil || !on {
		t.Fatalf("enabled file: got %v, %v", on, err)
	}
	if err := os.WriteFile(p, []byte("enableIdlenessWatcher=false\n"), 0644); err != nil {
		t.Fatal(err)
	}
	if on, _ := LXQtIdleWatcherEnabled(); on {
		t.Fatal("disabled file reported as enabled")
	}
}

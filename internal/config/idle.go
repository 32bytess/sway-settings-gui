func IdlePath() string       { return filepath.Join(SwayConfigDir(), "config.d", "idle.conf") }
func IdleScriptPath() string { return filepath.Join(SwayConfigDir(), "sway-settings", "idle.sh") }

// idleProcessName tags the swayidle this app starts, so it can be stopped
// without touching a swayidle the user runs themselves.
const idleProcessName = "sway-settings-idle"

// Idle configures swayidle and swaylock. Minutes of 0 disable that action.
type Idle struct {
	Enabled             bool
	LockMinutes         int
	ScreenOffMinutes    int
	SuspendMinutes      int
	LockBeforeSleep     bool
	LockColor           string // RRGGBB[AA], no leading #
	LockImage           string
	ShowFailedAttempts  bool
	IgnoreEmptyPassword bool
}

func defaultIdle() Idle {
	return Idle{LockMinutes: 5, ScreenOffMinutes: 10, LockBeforeSleep: true, LockColor: "000000"}
}

var lockColorRe = regexp.MustCompile(`^[0-9A-Fa-f]{6}([0-9A-Fa-f]{2})?$`)

const maxIdleMinutes = 7 * 24 * 60

func (i Idle) validate() error {
	for name, m := range map[string]int{"lock": i.LockMinutes, "screen off": i.ScreenOffMinutes, "suspend": i.SuspendMinutes} {
		if m < 0 || m > maxIdleMinutes {
			return fmt.Errorf("%s after %d minutes: must be between 0 (never) and %d", name, m, maxIdleMinutes)
		}
	}
	if !lockColorRe.MatchString(i.LockColor) {
		return fmt.Errorf("lock colour %q must be RRGGBB or RRGGBBAA", i.LockColor)
	}
	if hasControlChars(i.LockImage) {
		return fmt.Errorf("lock image path contains control characters")
	}
	return nil
}

// lockArgs is the swaylock command line as separate arguments.
func (i Idle) lockArgs() []string {
	args := []string{"swaylock", "-f", "-c", i.LockColor}
	if i.LockImage != "" {
		args = append(args, "-i", i.LockImage)
	}
	if i.ShowFailedAttempts {
		args = append(args, "-F")
	}
	if i.IgnoreEmptyPassword {
		args = append(args, "-e")
	}
	return args
}

var shellSafeRe = regexp.MustCompile(`^[A-Za-z0-9_./=:,+-]+$`)

// shQuote quotes s for a POSIX shell.
func shQuote(s string) string {
	if shellSafeRe.MatchString(s) {
		return s
	}
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}

func (i Idle) lockCommand() string {
	args := i.lockArgs()
	for n, a := range args {
		args[n] = shQuote(a)
	}
	return strings.Join(args, " ")
}

func yesNoStr(b bool) string {
	if b {
		return "yes"
	}
	return "no"
}

// script renders idle.sh. Settings are stored in the header so the app can
// read them back; the body restarts the tagged swayidle with them.
func (i Idle) script() string {
	var b strings.Builder
	b.WriteString("#!/bin/bash\n# Generated by sway-settings. Change these settings in the app.\n")
	for _, kv := range [][2]string{
		{"lock_minutes", strconv.Itoa(i.LockMinutes)},
		{"screen_off_minutes", strconv.Itoa(i.ScreenOffMinutes)},
		{"suspend_minutes", strconv.Itoa(i.SuspendMinutes)},
		{"lock_before_sleep", yesNoStr(i.LockBeforeSleep)},
		{"lock_color", i.LockColor},
		{"lock_image", i.LockImage},
		{"show_failed_attempts", yesNoStr(i.ShowFailedAttempts)},
		{"ignore_empty_password", yesNoStr(i.IgnoreEmptyPassword)},
	} {
		fmt.Fprintf(&b, "# %s=%s\n", kv[0], kv[1])
	}
	fmt.Fprintf(&b, "pkill -f '^%s( |$)'\n", idleProcessName)

	lock := shQuote(i.lockCommand())
	var actions []string
	if i.LockMinutes > 0 {
		actions = append(actions, fmt.Sprintf("timeout %d %s", i.LockMinutes*60, lock))
	}
	if i.ScreenOffMinutes > 0 {
		actions = append(actions, fmt.Sprintf(`timeout %d 'swaymsg "output * power off"' resume 'swaymsg "output * power on"'`, i.ScreenOffMinutes*60))
	}
	if i.SuspendMinutes > 0 {
		actions = append(actions, fmt.Sprintf("timeout %d 'systemctl suspend'", i.SuspendMinutes*60))
	}
	if i.LockBeforeSleep {
		actions = append(actions, "before-sleep "+lock)
	}
	b.WriteString("exec -a " + idleProcessName + " swayidle -w")
	for _, a := range actions {
		b.WriteString(" \\\n    " + a)
	}
	b.WriteString("\n")
	return b.String()
}

func (c *Config) loadIdle() error {
	data, _, err := readOptional(IdlePath())
	if err != nil {
		return err
	}
	for _, line := range splitLines(string(data)) {
		if strings.TrimSpace(line) == "exec_always "+IdleScriptPath() {
			c.Idle.Enabled = true
		}
	}
	script, _, err := readOptional(IdleScriptPath())
	if err != nil {
		return err
	}
	for _, line := range splitLines(string(script)) {
		kv, ok := strings.CutPrefix(line, "# ")
		if !ok {
			continue
		}
		key, val, ok := strings.Cut(kv, "=")
		if !ok {
			continue
		}
		atoi := func() int {
			n, err := strconv.Atoi(val)
			if err != nil {
				return -1 // rejected by validate, so a bad value can't be saved silently
			}
			return n
		}
		switch key {
		case "lock_minutes":
			c.Idle.LockMinutes = atoi()
		case "screen_off_minutes":
			c.Idle.ScreenOffMinutes = atoi()
		case "suspend_minutes":
			c.Idle.SuspendMinutes = atoi()
		case "lock_before_sleep":
			c.Idle.LockBeforeSleep = val == "yes"
		case "lock_color":
			c.Idle.LockColor = val
		case "lock_image":
			c.Idle.LockImage = val
		case "show_failed_attempts":
			c.Idle.ShowFailedAttempts = val == "yes"
		case "ignore_empty_password":
			c.Idle.IgnoreEmptyPassword = val == "yes"
		}
	}
	return nil
}

func (c *Config) validateIdle() error {
	if !c.Idle.Enabled {
		return nil
	}
	return c.Idle.validate()
}

// saveIdle writes the script and the exec_always line while enabled; while
// disabled idle.conf is emptied and the script is kept for its settings.
func (c *Config) saveIdle() error {
	if !c.Idle.Enabled {
		return writeLines(IdlePath(), nil)
	}
	if err := os.MkdirAll(filepath.Dir(IdleScriptPath()), 0755); err != nil {
		return err
	}
	if err := os.WriteFile(IdleScriptPath(), []byte(c.Idle.script()), 0755); err != nil {
		return err
	}
	// WriteFile keeps an existing file's mode, so make sure it's executable.
	if err := os.Chmod(IdleScriptPath(), 0755); err != nil {
		return err
	}
	return writeLines(IdlePath(), []string{"exec_always " + IdleScriptPath()})
}

// runCommand runs a program without a shell and returns its exit code. A
// variable so tests can replace it.
var runCommand = func(name string, args ...string) (int, error) {
	err := exec.Command(name, args...).Run()
	var exitErr *exec.ExitError
	if errors.As(err, &exitErr) {
		return exitErr.ExitCode(), nil
	}
	if err != nil {
		return -1, fmt.Errorf("running %s: %w", name, err)
	}
	return 0, nil
}

// StopIdle stops the swayidle this app started, if any.
func StopIdle() error {
	code, err := runCommand("pkill", "-f", "^"+idleProcessName+"( |$)")
	if err != nil {
		return err
	}
	if code > 1 { // 1 means nothing was running
		return fmt.Errorf("pkill failed with exit code %d", code)
	}
	return nil
}

// LockNow locks the screen with the configured swaylock options.
func LockNow(i Idle) error {
	if err := i.validate(); err != nil {
		return err
	}
	args := i.lockArgs()
	code, err := runCommand(args[0], args[1:]...)
	if err != nil {
		return err
	}
	if code != 0 {
		return fmt.Errorf("swaylock exited with code %d", code)
	}
	return nil
}

// LXQtIdleWatcherEnabled reports whether LXQt power management is set to act
// on idle, which would compete with swayidle.
func LXQtIdleWatcherEnabled() (bool, error) {
	home, err := os.UserHomeDir()
	if err != nil {
		return false, err
	}
	data, exists, err := readOptional(filepath.Join(home, ".config", "lxqt", "lxqt-powermanagement.conf"))
	if err != nil || !exists {
		return false, err
	}
	for _, line := range splitLines(string(data)) {
		if strings.TrimSpace(line) == "enableIdlenessWatcher=true" {
			return true, nil
		}
	}
	return false, nil
}
